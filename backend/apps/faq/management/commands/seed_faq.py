class Command(BaseCommand):
    help = '填充 FAQ 测试数据（分类 + 条目）'

    def add_arguments(self, parser):
        parser.add_argument('--clear', action='store_true', help='清空已有 FAQ 数据再填充')
        parser.add_argument('--category-only', action='store_true', help='仅填充分类')

    def handle(self, *args, **options):
        do_clear = options.get('clear')
        category_only = options.get('category_only')

        if do_clear:
            self.stdout.write(self.style.WARNING('清空已有 FAQ 数据...'))
            FAQItem.objects.all().delete()
            FAQCategory.objects.all().delete()

        # ── 填充分类 ──
        cat_map = {}
        for cat_data in CATEGORIES:
            cat, created = FAQCategory.objects.get_or_create(
                name=cat_data['name'],
                defaults=cat_data,
            )
            if not created:
                for k, v in cat_data.items():
                    setattr(cat, k, v)
                cat.save()
            cat_map[cat_data['name']] = cat

        self.stdout.write(self.style.SUCCESS(f'[OK] 分类: {FAQCategory.objects.count()} 个'))

        if category_only:
            return

        # ── 填充 FAQ 条目 ──
        now = timezone.now()
        created_count = 0

        for (
            question, answer, cat_idx, college_id,
            status, tags, frequency,
        ) in FAQ_ITEMS:
            category = list(cat_map.values())[cat_idx]
            college_id_val = college_id

            obj, created = FAQItem.objects.get_or_create(
                question=question,
                defaults={
                    'answer': answer,
                    'category': category,
                    'college_id': college_id_val,
                    'tags': tags,
                    'status': status,
                    'frequency': frequency,
                    'variant_count': 0,
                    'source_period_start': now - timedelta(days=30),
                    'source_period_end': now,
                    'related_doc_ids': [],
                },
            )
            if created:
                created_count += 1

        self.stdout.write(self.style.SUCCESS(
            f'[OK] FAQ 条目: {FAQItem.objects.count()} 条（本次新增 {created_count} 条）'
        ))

        # ── 汇总统计 ──
        status_counts = {}
        for s, _ in FAQItem.STATUS_CHOICES:
            cnt = FAQItem.objects.filter(status=s).count()
            if cnt:
                status_counts[s] = cnt

        college_counts = {}
        for cid, cname in COLLEGES.items():
            cnt = FAQItem.objects.filter(college_id=cid).count()
            if cnt:
                college_counts[cname] = cnt

        global_count = FAQItem.objects.filter(college__isnull=True).count()
        if global_count:
            college_counts['[全局通用]'] = global_count

        self.stdout.write(self.style.SUCCESS(f'[INFO] 状态分布: {status_counts}'))
        self.stdout.write(self.style.SUCCESS(f'[INFO] 学院分布: {college_counts}'))
        self.stdout.write(self.style.SUCCESS(
            '\n[OK] 测试数据就绪！管理员可通过以下入口管理 FAQ：\n'
            '  - Django Admin: /admin/faq/\n'
            '  - 管理端 API: /api/faq/manage/'
        ))
